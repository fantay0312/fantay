// Fantay: writes the engine and the icon set into Fantay Studio as one TypeScript module,
// studio/apps/web/src/vendor/kubai-icons/runtime.ts, with the licence beside it. Studio's guard
// forbids hand-written .js, so the classic scripts here stay the source and Studio gets a copy.
//
//   node scripts/sync-studio.mjs [--out dir]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const i = args.indexOf('--out');
const out = path.resolve(i >= 0 ? args[i + 1] : path.join(root, '../../studio/apps/web/src/vendor/kubai-icons'));
const read = (f) => fs.readFileSync(path.join(root, f), 'utf8').replace(/\s+$/, '');

const source = [
  '// @ts-nocheck -- generated by fantay-design/tools/feature-icons/scripts/sync-studio.mjs from src/engine.js and',
  '// src/icons.js. Do not edit here: change those files and run the script again (see README.md).',
  read('src/engine.js'),
  '',
  read('src/icons.js'),
  '',
  'export { ICONS, ICON_VIEWBOX, DUR, runtime, clearTone, flatTone, FANTAY_INK, mountIcon, targetOf, render, go, recolor };',
  ''
].join('\n');

fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'runtime.ts'), source);
fs.copyFileSync(path.join(root, 'LICENSE'), path.join(out, 'LICENSE'));
const names = [...read('src/icons.js').matchAll(/\bname:\s*'([^']+)'/g)].map((m) => m[1]);
console.log(`Wrote ${names.length} icons to ${path.join(out, 'runtime.ts')}`);
